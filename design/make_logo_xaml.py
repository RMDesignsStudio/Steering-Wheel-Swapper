"""Converts the RM Designs SVG logos (../branding, read only) into WPF DrawingImages:
src/WheelSwap.App/Brand.xaml (keys: Wordmark, RmIcon). Path data is re-tokenised so WPF's path parser accepts it."""
import pathlib
import re
import xml.etree.ElementTree as ET

here = pathlib.Path(__file__).parent
brand = here.parent / "branding"
out = here.parent / "src" / "WheelSwap.App" / "Brand.xaml"
NS = "{http://www.w3.org/2000/svg}"
TOKEN = re.compile(r"[MmLlHhVvCcSsQqTtAaZz]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")


def styles(root):
    css = "".join(s.text or "" for s in root.iter(NS + "style"))
    rules = {}
    for cls, body in re.findall(r"\.([\w-]+)\s*\{([^}]*)\}", css):
        rules[cls] = dict((k.strip(), v.strip()) for k, v in (p.split(":") for p in body.split(";") if ":" in p))
    return rules


def drawing(svg_name, key):
    root = ET.parse(brand / svg_name).getroot()
    rules = styles(root)
    x0, y0, w, h = (float(v) for v in root.get("viewBox").split())
    parts = []
    for p in root.iter(NS + "path"):
        st = rules.get(p.get("class", ""), {})
        fill = st.get("fill", "#000000")
        stroke = st.get("stroke")
        data = " ".join(TOKEN.findall(p.get("d")))
        brush = "" if fill == "none" else f' Brush="{fill}"'
        pen = f'<GeometryDrawing.Pen><Pen Brush="{stroke}" Thickness="{st.get("stroke-width", "1").replace("px", "")}" MiterLimit="10"/></GeometryDrawing.Pen>' if stroke else ""
        parts.append(f'        <GeometryDrawing{brush} Geometry="{data}">{pen}</GeometryDrawing>' if pen else f'        <GeometryDrawing{brush} Geometry="{data}"/>')
    # a transparent rectangle pins the drawing to the SVG viewBox
    frame = f'        <GeometryDrawing Brush="Transparent"><GeometryDrawing.Geometry><RectangleGeometry Rect="{x0},{y0},{w},{h}"/></GeometryDrawing.Geometry></GeometryDrawing>'
    return f'  <DrawingImage x:Key="{key}">\n    <DrawingImage.Drawing>\n      <DrawingGroup>\n{frame}\n' + "\n".join(parts) + "\n      </DrawingGroup>\n    </DrawingImage.Drawing>\n  </DrawingImage>"


xaml = ('<!-- generated by design/make_logo_xaml.py from branding/*.svg; do not edit by hand -->\n'
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n'
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n'
        + drawing("RM Designs Text on Purple.svg", "Wordmark") + "\n"
        + drawing("RM Designs Icon on Purple.svg", "RmIcon") + "\n"
        + drawing("RM Designs Icon on White.svg", "RmIconOnWhite") + "\n</ResourceDictionary>\n")
out.write_text(xaml, encoding="utf-8")
print("wrote", out, len(xaml) // 1024, "KB")
