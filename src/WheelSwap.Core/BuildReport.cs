    /// <summary>A ~256 px PNG preview (data URI) of a texture in an ERP (external .mipmaps read from the game), or null.</summary>
    static string? Thumb(ErpFile erp, string srvId, GameData game, bool keepAlpha) => TexturePng(erp, srvId, game, 256, keepAlpha);

    /// <summary>A texture as a PNG data URI at the largest mip level not above <paramref name="maxSize"/>, or null.</summary>
    internal static string? TexturePng(ErpFile erp, string srvId, GameData game, int maxSize, bool keepAlpha)
    {
        var r = erp.Resources.FirstOrDefault(x => x.Identifier == srvId);
        if (r is null) return null;
        var srv = new ErpGfxSRVResource();
        srv.FromResource(r);
        Stream? mips = null;
        if (srv.SurfaceRes.HasMips && srv.SurfaceRes.HasValidMips && game.MipmapsPath(srv.SurfaceRes.Frag2.MipMapFileName) is { } mp)
            mips = File.OpenRead(mp);
        EgoEngineLibrary.Graphics.Dds.DdsFile dds;
        using (mips) dds = srv.ToDdsFile(mips, false, 0);
        using var ms = new MemoryStream();
        dds.Write(ms);
        ms.Position = 0;
        var levels = new BcDecoder().DecodeAllMipMaps2D(ms);
        var img = levels.FirstOrDefault(l => l.Width <= maxSize && l.Height <= maxSize);
        if (img.IsEmpty) img = levels[^1];
        var span = img.Span;
        var rgba = new byte[img.Width * img.Height * 4];
        for (int y = 0; y < img.Height; y++)
            MemoryMarshal.AsBytes(span.GetRowSpan(y)).CopyTo(rgba.AsSpan(y * img.Width * 4));
        if (!keepAlpha) for (int i = 3; i < rgba.Length; i += 4) rgba[i] = 255;
        return "data:image/png;base64," + Convert.ToBase64String(Png(img.Width, img.Height, rgba));
    }

    /// <summary>Minimal RGBA PNG writer (no filtering).</summary>
    internal static byte[] Png(int w, int h, byte[] rgba)
    {
        using var raw = new MemoryStream();
        using (var z = new ZLibStream(raw, CompressionLevel.Optimal, leaveOpen: true))
            for (int y = 0; y < h; y++) { z.WriteByte(0); z.Write(rgba, y * w * 4, w * 4); }
        using var png = new MemoryStream();
        png.Write([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
        var ihdr = new byte[13];
        System.Buffers.Binary.BinaryPrimitives.WriteInt32BigEndian(ihdr, w);
        System.Buffers.Binary.BinaryPrimitives.WriteInt32BigEndian(ihdr.AsSpan(4), h);
        ihdr[8] = 8; ihdr[9] = 6;   // 8-bit RGBA
        Chunk(png, "IHDR", ihdr);
        Chunk(png, "IDAT", raw.ToArray());
        Chunk(png, "IEND", []);
        return png.ToArray();
    }

    static void Chunk(Stream s, string type, byte[] data)
    {
        var len = new byte[4];
        System.Buffers.Binary.BinaryPrimitives.WriteInt32BigEndian(len, data.Length);
        s.Write(len);
        var body = Encoding.ASCII.GetBytes(type).Concat(data).ToArray();
        s.Write(body);
        var crc = new byte[4];
        System.Buffers.Binary.BinaryPrimitives.WriteUInt32BigEndian(crc, Crc32(body));
        s.Write(crc);
    }

    static readonly uint[] CrcTable = Enumerable.Range(0, 256).Select(n =>
    {
        uint c = (uint)n;
        for (int k = 0; k < 8; k++) c = (c & 1) != 0 ? 0xEDB88320u ^ (c >> 1) : c >> 1;
        return c;
    }).ToArray();

    static uint Crc32(byte[] d)
    {
        uint c = 0xFFFFFFFFu;
        foreach (var b in d) c = CrcTable[(c ^ b) & 0xFF] ^ (c >> 8);
        return c ^ 0xFFFFFFFFu;
    }

    static string E(string s) => WebUtility.HtmlEncode(s);

    /// <summary>The RM Designs wordmark (embedded SVG), or the name in text if it is missing.</summary>
    static string Wordmark()
    {
        using var st = typeof(BuildReport).Assembly.GetManifestResourceStream("wordmark.svg");
        if (st is null) return "<b>RM DESIGNS</b>";
        var svg = new StreamReader(st).ReadToEnd();
        return svg[svg.IndexOf("<svg", StringComparison.Ordinal)..].Replace("<svg ", "<svg class=\"wordmark\" ");
    }

