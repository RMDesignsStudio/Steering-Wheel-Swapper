/// <summary>
/// A self-contained HTML page about one build: for every car, the wheel before and after (front + side views drawn
/// from the real geometry), the wheel textures before and after, what went in at each detail level, the verification
/// result and the warnings. Written next to the output as "&lt;output&gt; - report.html".
/// </summary>
public static class BuildReport
{
    public static string PathFor(string outPath) =>
        Path.Combine(Path.GetDirectoryName(Path.GetFullPath(outPath))!, Path.GetFileNameWithoutExtension(outPath) + " - report.html");

    /// <summary>Write the report for a finished build and return its path.</summary>
    public static string Write(GameData game, SerpsTemplate tpl, BuildResult res, SwapLog log, string outPath)
    {
        var path = PathFor(outPath);
        File.WriteAllText(path, Html(game, tpl, res, log, outPath), new UTF8Encoding(false));
        return path;
    }

    public static string Html(GameData game, SerpsTemplate tpl, BuildResult res, SwapLog log, string? outPath)
    {
        var sb = new StringBuilder();
        string donor = GameData.DonorName(res.DonorToken);
        int checks = res.Verification.Sum(v => v.Checks);
        bool ok = res.Verification.All(v => v.Ok) && res.Verification.Count == res.Entries.Count;
        sb.Append($$"""
            <!doctype html>
            <html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
            <title>Wheel swap report</title>
            <style>{{Css}}{{WheelPreview.Css}}</style></head><body>
            <div class="band"><div class="band-in">{{Wordmark()}}<span>Build report</span></div></div>
            <header>
              <h1>{{E(donor)}} wheel <span class="arrow">→</span> {{E(tpl.Name)}}</h1>
              <div class="meta">
                <span>*{{res.Entries.Count}} car{{(res.Entries.Count == 1 ? "" : "s")}}</span>
                <span>{{(outPath is null ? "dry run (nothing written)" : E(Path.GetFileName(outPath)))}}</span>
                <span>{{DateTime.Now.ToString("d MMM yyyy, HH:mm", CultureInfo.InvariantCulture)}}</span>
              </div>
              <div class="badge {{(ok ? "ok" : "bad")}}">{{(ok ? $"Verified · {checks} checks passed" : "Verification failed")}}</div>
              <div class="rule"></div>
            </header>
            <main>
            """);

        var segments = Segments(log);
        for (int i = 0; i < res.Entries.Count; i++)
        {
            var be = res.Entries[i];
            var v = i < res.Verification.Count ? res.Verification[i] : null;
            var lines = segments.GetValueOrDefault(be.Entry.FileName) ?? [];
            try { Entry(sb, game, tpl, res, be, v, lines); }
            catch (Exception ex)
            {
                sb.Append($"<section class=\"car\"><h2>{E(be.Entry.Describe)}</h2><p class=\"warn\">This part of the report could not be drawn: {E(ex.Message)}</p></section>");
            }
        }
        var general = log.Warnings.Where(w => !res.Entries.Any(b => w.StartsWith(b.Entry.FileName, StringComparison.Ordinal))
                                              && !segments.Values.Any(s => s.Contains("WARNING: " + w))).Distinct().ToList();
        if (general.Count > 0)
            sb.Append("<section class=\"car\"><h2>Other notes</h2><ul class=\"warnings\">")
              .AppendJoin("", general.Select(w => $"<li>{E(w)}</li>")).Append("</ul></section>");
        sb.Append("</main><footer>Generated by Steering Wheel Swapper. Your template was not changed.</footer></body></html>");
        return sb.ToString();
    }

    // ---------------------------------------------------------------- one car

    static void Entry(StringBuilder sb, GameData game, SerpsTemplate tpl, BuildResult res, BuiltEntry be, VerifyResult? v, List<string> lines)
    {
        var target = tpl.LoadModel(game, be.Entry);
        var outErp = ErpX.Load(res.Replaced[be.Entry.ZipPath]);
        var after = new CarModel(game, be.PrivateToken, [ErpX.Load(res.Replaced[be.Entry.ZipPath])]);
        int origIb = target.Buf(target.Mesh("?lod=0&mesh").IndexBuffer).Count;

        // the lowest detail level both cars have that keeps the page small
        int lod = new[] { 1, 0, 2, 3 }.FirstOrDefault(l => Count(BeforeTris(target, l)) is > 0 and <= 9000 && Count(AfterTris(after, l, origIb)) is > 0 and <= 9000, 0);
        var before = BeforeTris(target, lod);
        var aft = AfterTris(after, lod, origIb);

        string badge = v is null ? "<span class=\"badge\">not verified</span>"
            : v.Ok ? $"<span class=\"badge ok\">Verified · {v.Checks} checks</span>"
            : $"<span class=\"badge bad\">{v.Failures.Count} check{(v.Failures.Count == 1 ? "" : "s")} failed</span>";
        var targetName = be.Entry.Kind == EntryKind.TeamChassis ? GameData.TeamName(be.Entry.SlotToken ?? be.ModelToken) : "FOM chassis";
        sb.Append($"""
            <section class="car">
              <div class="car-head"><h2>{E(be.Entry.Describe.Split("  —")[0])}</h2>{badge}</div>
              <div class="file">{E(be.Entry.FileName)}</div>
            """);
        if (v is { Ok: false })
            sb.Append("<ul class=\"failures\">").AppendJoin("", v.Failures.Select(f => $"<li>{E(f)}</li>")).Append("</ul>");

        // wheel pictures
        var all = before.Concat(aft).ToList();
        sb.Append($"""
              <h3>Wheel <span class="muted">· detail level {lod}, drawn from the game geometry</span></h3>
              <div class="views">
                <figure><figcaption>Before · {E(targetName)} wheel</figcaption>{Svg(before, all, Front)}{Svg(before, all, Side)}</figure>
                <figure><figcaption>After · {E(GameData.DonorName(be.DonorToken))} wheel</figcaption>{Svg(aft, all, Front)}{Svg(aft, all, Side)}</figure>
              </div>
              <div class="legend">{string.Join("", Palette.Select(p => $"<span><i style=\"background:{p.Value}\"></i>{E(p.Key)}</span>"))}</div>
            """);

        // textures
        var origErp = ErpX.Load(tpl.Get(be.Entry.ZipPath));
        var gameErps = new[] { be.Entry.SlotToken, be.ModelToken }.Where(t => t is not null && File.Exists(game.TeamErp(t)))
                                                                    .Select(t => new Lazy<ErpFile>(() => ErpX.Load(game.TeamErp(t!)))).ToList();
        // interactive 3D view of the new wheel (and the old one), textured
        try { sb.Append("<h3>3D preview <span class=\"muted\">· drag to turn, scroll to zoom</span></h3>").Append(WheelPreview.Section(game, tpl, res, be, "pv-" + be.PrivateToken)); }
        catch (Exception ex) { sb.Append($"<p class=\"muted small\">3D preview not available: {E(ex.Message)}</p>"); }

        sb.Append("<h3>Wheel textures</h3><div class=\"textures\">");
        foreach (var ch in new[] { "d", "n", "s", "decals_da" })
        {
            var id = be.TextureIds.FirstOrDefault(t => TextureSwap.ChannelOf(t) == ch);
            if (id is null) continue;
            string? was = null, now = null;
            try { now = Thumb(outErp, id, game, ch == "decals_da"); } catch { }
            try { was = Thumb(origErp, id, game, ch == "decals_da") ?? gameErps.Select(g => Thumb(g.Value, id, game, ch == "decals_da")).FirstOrDefault(x => x is not null); } catch { }
            sb.Append($"""
                <div class="tex"><div class="tex-name">{ChannelName(ch)}</div>
                  <div class="pair">{Img(was, "before")}{Img(now, "after")}</div>
                  <div class="tex-file">{E(id.Split('/')[^1])}{(be.DonorTextureSizes.TryGetValue(ch, out var sz) ? $" · {sz.W}×{sz.H}" : "")}</div></div>
                """);
        }
        sb.Append("</div>");

        // what went in per detail level
        var rows = lines.Select(l => LodLine.Match(l)).Where(m => m.Success).ToList();
        if (rows.Count > 0)
        {
            // one row per wheel slot, triangles per detail level
            var lods = rows.Select(m => int.Parse(m.Groups[1].Value)).Distinct().Order().ToList();
            sb.Append("<h3>Donor geometry added <span class=\"muted\">· triangles per detail level</span></h3><table><thead><tr><th>Wheel slot</th>")
              .AppendJoin("", lods.Select(l => $"<th>LOD{l}</th>")).Append("</tr></thead><tbody>");
            foreach (var slot in rows.Select(m => m.Groups[2].Value).Distinct())
            {
                sb.Append($"<tr><td>{E(slot)}</td>");
                foreach (var l in lods)
                {
                    var m = rows.FirstOrDefault(r => r.Groups[2].Value == slot && r.Groups[1].Value == l.ToString(CultureInfo.InvariantCulture));
                    sb.Append(m is null ? "<td class=\"muted\">–</td>" : $"<td>{int.Parse(m.Groups[4].Value):N0}</td>");
                }
                sb.Append("</tr>");
            }
            sb.Append("</tbody></table>");
        }
        var notes = lines.Where(l => l.Contains(" drawn with the target's ") || l.Contains(" left out") || l.StartsWith("Earlier Steering Wheel Swapper")).ToList();
        var warnings = lines.Where(l => l.StartsWith("WARNING: ")).Select(l => l["WARNING: ".Length..]).Concat(v?.Warnings ?? []).Distinct().ToList();
        if (warnings.Count > 0)
            sb.Append("<h3>Warnings</h3><ul class=\"warnings\">").AppendJoin("", warnings.Select(w => $"<li>{E(w)}</li>")).Append("</ul>");
        if (notes.Count > 0)
            sb.Append("<h3>Notes</h3><ul class=\"notes\">").AppendJoin("", notes.Where(n => !n.StartsWith("WARNING")).Select(n => $"<li>{E(n)}</li>")).Append("</ul>");
        var anim = lines.FirstOrDefault(l => l.StartsWith("Driver animation "));
        if (anim is not null) sb.Append($"<p class=\"muted small\">{E(anim)}</p>");
        sb.Append("<details><summary>Full log for this car</summary><pre>")
          .AppendJoin("\n", lines.Select(l => l.StartsWith("WARNING: ") ? $"<span class=\"w\">{E(l)}</span>" : E(l)))
          .Append("</pre></details></section>");
    }

    static readonly Regex LodLine = new(@"^LOD(\d) '([^']+)': (\d+) donor vertices, (\d+) triangles", RegexOptions.Compiled);

    /// <summary>Log lines per entry file name (the build logs "=== file (...) ===" before each car).</summary>
    static Dictionary<string, List<string>> Segments(SwapLog log)
    {
        var d = new Dictionary<string, List<string>>();
        List<string>? cur = null;
        foreach (var l in log.All)
        {
            if (l.StartsWith("=== ") && l.EndsWith(" ===")) { var f = l[4..].Split(' ')[0]; d[f] = cur = []; continue; }
            if (l.StartsWith("Verified: ") || l.StartsWith("Wrote ") || l.StartsWith("Dry run")) { cur = null; continue; }
            cur?.Add(l);
        }
        return d;
    }

    static string ChannelName(string ch) => ch switch { "d" => "Colour", "n" => "Normal", "s" => "Specular", _ => "Decals" };

    static string Img(string? src, string label) => src is null
        ? $"<div class=\"img none\"><span>{label}<br>not in the template</span></div>"
        : $"<div class=\"img\"><img src=\"{src}\" alt=\"{label}\" loading=\"lazy\"><span>{label}</span></div>";

