    readonly record struct Tri(Vector3 A, Vector3 B, Vector3 C, string Piece);

    static int Count(List<Tri> t) => t.Count;

    static readonly Dictionary<string, string> Palette = new()
    {
        ["Wheel body"] = "#9aa3ad", ["Carbon"] = "#596070", ["Screen"] = "#3fb6ff", ["Lights / flag"] = "#f2b544",
        ["Number"] = "#f4f4f4", ["Paddles"] = "#c58cff", ["Dials"] = "#7ee08a", ["Other"] = "#8a7f74",
    };

    static string PieceOf(string slot, string bone)
    {
        if (bone.Contains("paddle", StringComparison.OrdinalIgnoreCase)) return "Paddles";
        if (bone.Contains("dial", StringComparison.OrdinalIgnoreCase)) return "Dials";
        var s = WheelGrafter.NormSlot(slot);
        return s.StartsWith("steeringwheel") ? "Wheel body"
             : s.StartsWith("carbon") ? "Carbon"
             : s is "lcd" ? "Screen"
             : s is "digirevs" or "flag" ? "Lights / flag"
             : s is "number" ? "Number" : "Other";
    }

    /// <summary>The target car's own wheel family at a detail level (as the car had it before the swap).</summary>
    static List<Tri> BeforeTris(CarModel car, int lod)
    {
        var nt = NodeTable.Parse(car.Render);
        var tris = new List<Tri>();
        foreach (var part in WheelGrafter.Family)
        {
            var m = car.TryMesh($"?lod={lod}&{part}&mesh");
            if (m is null || m.Empty) continue;
            foreach (var s in m.Subs.Where(s => s.ICount > 0)) AddTris(car, nt, m, s, tris);
        }
        return tris;
    }

    /// <summary>The donor wheel appended into the private model at a detail level.</summary>
    static List<Tri> AfterTris(CarModel car, int lod, int origIbCount)
    {
        var nt = NodeTable.Parse(car.Render);
        var tris = new List<Tri>();
        var m = car.TryMesh($"?lod={lod}&mesh");
        if (m is null || m.Empty) return tris;
        foreach (var s in m.Subs.Where(s => s.ICount > 0 && s.IOff >= origIbCount)) AddTris(car, nt, m, s, tris);
        return tris;
    }

    /// <summary>Triangles of one submesh in steering-wheel space: each vertex is placed by its bone (paddles and
    /// dials are modelled around their own pivots), relative to the steering_wheel node.</summary>
    static void AddTris(CarModel car, NodeTable nt, MeshDesc m, SubMesh s, List<Tri> into)
    {
        var streams = m.StreamEaids(s);
        var pe = streams.FirstOrDefault(e => car.Buf(e).Fvf == BufInfo.FvfPosition);
        if (pe is null) return;
        var be = streams.FirstOrDefault(e => car.Buf(e).Fvf == BufInfo.FvfBones);
        var pos = MemoryMarshal.Cast<byte, float>(car.Frags(pe)[1]).ToArray();
        var bones = be is null ? null : car.Frags(be)[1];
        int bStride = be is null ? 0 : car.Buf(be).Stride;
        var ibData = car.Frags(m.IndexBuffer)[1];
        bool wide = car.Buf(m.IndexBuffer).Stride == 4;
        uint Idx(int i) => wide ? BitConverter.ToUInt32(ibData, i * 4) : BitConverter.ToUInt16(ibData, i * 2);

        var world = new Dictionary<int, Matrix4x4>();
        Matrix4x4 World(int n)
        {
            if (world.TryGetValue(n, out var w)) return w;
            var x = nt.Nodes[n];
            var local = Matrix4x4.CreateScale(x.S[0], x.S[1], x.S[2]) * Matrix4x4.CreateFromQuaternion(new Quaternion(x.Q[0], x.Q[1], x.Q[2], x.Q[3])) *
                        Matrix4x4.CreateTranslation(x.T[0], x.T[1], x.T[2]);
            return world[n] = x.Parent >= 0 ? local * World(x.Parent) : local;
        }
        var swNode = nt.SteeringCluster().TryGetValue(("steering_wheel", "steer_master"), out var sw) ? sw : nt.SteerMaster;
        Matrix4x4.Invert(World(swNode.Index), out var toWheel);
        var toWheelByBone = new Dictionary<int, Matrix4x4>();

        (Vector3 P, string Bone) Vert(uint idx)
        {
            int vi = (int)idx + s.VOff;
            int node = bones is not null && bones[vi * bStride] < nt.Palette.Length ? nt.Palette[bones[vi * bStride]] : swNode.Index;
            if (!toWheelByBone.TryGetValue(node, out var mtx)) toWheelByBone[node] = mtx = World(node) * toWheel;
            return (Vector3.Transform(new Vector3(pos[vi * 3], pos[vi * 3 + 1], pos[vi * 3 + 2]), mtx), nt.Nodes[node].Name);
        }
        for (int i = s.IOff; i + 2 < s.IOff + s.ICount; i += 3)
        {
            uint a = Idx(i), b = Idx(i + 1), c = Idx(i + 2);
            if (a == b || b == c || a == c) continue;   // hidden (degenerate) triangles
            var (pa, bone) = Vert(a);
            into.Add(new Tri(pa, Vert(b).P, Vert(c).P, PieceOf(s.Name, bone)));
        }
    }

    // views in steering-wheel space (X across the car, Y up, Z along the car; the driver sits at -Z)
    // -> (screen x, screen y up, depth: larger = further from the viewer)
    static (float X, float Y, float D) Front(Vector3 p) => (-p.X, p.Y, p.Z);
    static (float X, float Y, float D) Side(Vector3 p) => (-p.Z, p.Y, -p.X);

    static string Svg(List<Tri> tris, List<Tri> frame, Func<Vector3, (float X, float Y, float D)> view)
    {
        const int W = 320, H = 220, Pad = 10;
        if (tris.Count == 0) return $"<svg class=\"view\" viewBox=\"0 0 {W} {H}\"><text x=\"{W / 2}\" y=\"{H / 2}\" text-anchor=\"middle\" fill=\"#9097A3\" font-size=\"12\">no geometry</text></svg>";
        float minX = float.MaxValue, maxX = float.MinValue, minY = float.MaxValue, maxY = float.MinValue;
        foreach (var t in frame)
            foreach (var p in new[] { t.A, t.B, t.C })
            {
                var (x, y, _) = view(p);
                minX = Math.Min(minX, x); maxX = Math.Max(maxX, x); minY = Math.Min(minY, y); maxY = Math.Max(maxY, y);
            }
        float scale = Math.Min((W - 2 * Pad) / Math.Max(1e-4f, maxX - minX), (H - 2 * Pad) / Math.Max(1e-4f, maxY - minY));
        float ox = (W - (maxX - minX) * scale) / 2, oy = (H - (maxY - minY) * scale) / 2;
        var light = Vector3.Normalize(new Vector3(-0.35f, 0.55f, -1f));
        var proj = tris.Select(t =>
        {
            var a = view(t.A); var b = view(t.B); var c = view(t.C);
            var n = Vector3.Cross(new Vector3(b.X - a.X, b.Y - a.Y, b.D - a.D), new Vector3(c.X - a.X, c.Y - a.Y, c.D - a.D));
            float shade = n.LengthSquared() < 1e-20f ? 0.6f : 0.38f + 0.62f * MathF.Abs(Vector3.Dot(Vector3.Normalize(n), light));
            return (a, b, c, Depth: (a.D + b.D + c.D) / 3, Shade: shade, t.Piece);
        }).OrderByDescending(t => t.Depth);
        var sb = new StringBuilder($"<svg class=\"view\" viewBox=\"0 0 {W} {H}\" shape-rendering=\"crispEdges\">");
        string P((float X, float Y, float D) q) => string.Create(CultureInfo.InvariantCulture, $"{ox + (q.X - minX) * scale:0.#},{H - (oy + (q.Y - minY) * scale):0.#}");
        foreach (var t in proj)
        {
            var hex = Palette[t.Piece];
            int r = Convert.ToInt32(hex[1..3], 16), g = Convert.ToInt32(hex[3..5], 16), b = Convert.ToInt32(hex[5..7], 16);
            string col = $"#{(int)(r * t.Shade):x2}{(int)(g * t.Shade):x2}{(int)(b * t.Shade):x2}";
            sb.Append($"<path d=\"M{P(t.a)}L{P(t.b)}L{P(t.c)}Z\" fill=\"{col}\" stroke=\"{col}\" stroke-width=\".4\"/>");
        }
        return sb.Append("</svg>").ToString();
    }

